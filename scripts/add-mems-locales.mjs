const files = fs.readdirSync(localesDir).filter((f) => f.endsWith(".json") && f !== "en.json");

let updated = 0;
let skipped = 0;

for (const file of files) {
  const filePath = path.join(localesDir, file);
  const locale = JSON.parse(fs.readFileSync(filePath, "utf-8"));

  if (locale.mems) {
    skipped++;
    continue;
  }

  const key = file.replace(".json", "");
  locale.mems = TRANSLATIONS[key] ?? EN;

  fs.writeFileSync(filePath, JSON.stringify(locale, null, 2) + "\n");
  updated++;
}

console.log(`Updated: ${updated}, Skipped (already have mems): ${skipped}`);
