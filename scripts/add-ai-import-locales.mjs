let skipped = 0;

for (const file of files) {
  const filePath = path.join(localesDir, file);
  const locale = JSON.parse(fs.readFileSync(filePath, "utf-8"));

  if (locale.createEdit?.aiImportButton) {
    skipped++;
    continue;
  }

  const key = file.replace(".json", "");
  const translations = TRANSLATIONS[key] ?? EN;

  locale.createEdit = { ...locale.createEdit, ...translations };

  fs.writeFileSync(filePath, JSON.stringify(locale, null, 2) + "\n");
  updated++;
}

